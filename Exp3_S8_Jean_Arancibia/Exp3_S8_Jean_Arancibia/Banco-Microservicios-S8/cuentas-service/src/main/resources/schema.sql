CREATE TABLE IF NOT EXISTS cuentas (
 cuenta_id BIGINT PRIMARY KEY, nombre VARCHAR(120) NOT NULL, saldo DECIMAL(15,2) NOT NULL,
 edad INT NOT NULL, tipo VARCHAR(20) NOT NULL, interes_calculado DECIMAL(15,2) NOT NULL, saldo_final DECIMAL(15,2) NOT NULL
);
CREATE TABLE IF NOT EXISTS transacciones (
 id BIGINT PRIMARY KEY, fecha DATE NOT NULL, monto DECIMAL(15,2) NOT NULL, tipo VARCHAR(20) NOT NULL
);
CREATE TABLE IF NOT EXISTS movimientos_anuales (
 id BIGINT PRIMARY KEY, cuenta_id BIGINT NOT NULL, fecha DATE NOT NULL,
 transaccion VARCHAR(20) NOT NULL, monto DECIMAL(15,2) NOT NULL, descripcion VARCHAR(255) NOT NULL
);
CREATE TABLE IF NOT EXISTS migracion_lote (
 id VARCHAR(64) PRIMARY KEY, importado_en TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS solicitudes_reporte (
 id VARCHAR(36) PRIMARY KEY, estado VARCHAR(20) NOT NULL,
 creado_en TIMESTAMP NOT NULL, completado_en TIMESTAMP NULL, resultado TEXT NULL
);
CREATE TABLE IF NOT EXISTS eventos_outbox (
 id VARCHAR(36) PRIMARY KEY, pendiente BOOLEAN NOT NULL,
 intentos INT NOT NULL DEFAULT 0, ultimo_envio TIMESTAMP NULL
);
